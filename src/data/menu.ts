/** Giá thấp nhất của một món — dùng để hiển thị "từ …" với món nhiều size. */
export function dishFromPrice(d: Dish): number {
  if (typeof d.price === "number") return d.price;
  if (d.variants?.length) return Math.min(...d.variants.map((v) => v.price));
  return 0;
}

